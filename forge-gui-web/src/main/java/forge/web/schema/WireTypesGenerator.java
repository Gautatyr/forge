package forge.web.schema;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

import forge.web.bridge.WireSchema.Kind;

/**
 * Emits the frontend's TypeScript wire types ({@code frontend/src/wire/generated/wire.ts}) from {@link WireModel}.
 * Run by the forge-gui-web Maven build (process-classes): {@code check} mode fails the build when the
 * committed file differs from what the engine produces; {@code write} mode rewrites it.
 */
public final class WireTypesGenerator {

    static final String REGENERATE = "mvn -pl forge-gui-web -am process-classes -Dwire.types=write";

    private WireTypesGenerator() { }

    /** Args: {@code check|write}, the committed file, where to write the fresh output in check mode. */
    public static void main(String[] args) {
        if (args.length != 3) {
            throw new IllegalArgumentException("usage: WireTypesGenerator check|write <committed wire.ts> <fresh output>");
        }
        run(args[0], Path.of(args[1]), Path.of(args[2]));
    }

    static void run(String mode, Path committed, Path fresh) {
        if (!"check".equals(mode) && !"write".equals(mode)) {
            throw new IllegalArgumentException("mode must be check or write, got " + mode);
        }
        String ts = render(WireModel.fromEngine());
        try {
            if ("write".equals(mode)) {
                Files.createDirectories(committed.toAbsolutePath().getParent());
                Files.writeString(committed, ts, StandardCharsets.UTF_8);
                return;
            }
            Files.createDirectories(fresh.toAbsolutePath().getParent());
            Files.writeString(fresh, ts, StandardCharsets.UTF_8);
            String current = Files.exists(committed) ? Files.readString(committed, StandardCharsets.UTF_8).replace("\r\n", "\n") : null;
            if (!ts.equals(current)) {
                throw new IllegalStateException(committed + " is stale: the engine's wire types changed (fresh output: "
                        + fresh + "). Regenerate with: " + REGENERATE + " and commit it.");
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    public static String render(WireModel m) {
        Out o = new Out();
        o.line("// GENERATED by forge.web.schema.WireTypesGenerator from the engine. Do not edit.");
        o.line("// Regenerate: " + REGENERATE);
        o.line("// Import only from src/wire/ (the adapter); components use the UI view-model.");
        o.blank();
        o.line("export const WIRE_VERSION = " + WireEnvelope.VERSION + ";");

        o.section("References: ids of wire objects");
        for (WireModel.ObjectType t : WireModel.OBJECT_TYPES) {
            if (!o.has("export type " + t.idType() + " ")) {
                o.line("export type " + t.idType() + " = number;");
            }
        }
        o.blank();
        o.line("/** GameEntityView reference. */");
        o.block("export interface EntityRef", List.of("type: 'card' | 'player';", "id: number;"));
        o.line("/** One combat band of the game's CombatView. */");
        o.block("export interface CombatBand", List.of(
                "attackers: CardId[];", "defender: EntityRef;", "blockers: CardId[];", "plannedBlockers: CardId[];"));
        o.line("/** IPaperCard: name, edition code, collector number. */");
        o.block("export interface PaperCardRef", List.of("name: string;", "set: string;", "cn: string;"));

        o.section("Engine enums, by constant name");
        for (WireModel.EnumType e : m.enums().values()) {
            o.line("/** " + e.javaName() + " */");
            o.union("export type " + e.tsName() + " =", e.constants());
        }

        o.section("Properties (TrackableProperty), absent = engine default");
        List<String> kinds = new ArrayList<>();
        for (Kind k : Kind.values()) {
            kinds.add(k.name().toLowerCase(Locale.ROOT));
        }
        o.union("export type WireKind =", kinds);
        o.line("/** Wire kind of every property; the runtime hello.schema should be equal. */");
        List<String> kindLines = new ArrayList<>();
        for (WireModel.Property p : m.properties()) {
            kindLines.add(p.name() + ": '" + p.kind().name().toLowerCase(Locale.ROOT) + "',");
        }
        o.block("export const PROPERTY_KINDS =", kindLines, " as const satisfies Record<string, WireKind>;");
        o.line("export type PropertyName = keyof typeof PROPERTY_KINDS;");
        o.blank();
        o.line("/** Every property with its value type. */");
        o.block("export interface WireProps", props(m, null));
        for (WireModel.ObjectType t : WireModel.OBJECT_TYPES) {
            o.line("/** Properties of `" + t.name() + "` objects (" + t.view().getSimpleName() + "). */");
            o.block("export interface " + t.propsType(), props(m, t.name()));
        }

        o.section("Objects");
        List<String> typeNames = new ArrayList<>();
        List<String> objects = new ArrayList<>();
        List<String> patches = new ArrayList<>();
        for (WireModel.ObjectType t : WireModel.OBJECT_TYPES) {
            typeNames.add(t.name());
            String head = "{ type: '" + t.name() + "'; id: " + t.idType() + "; "
                    + ("cardState".equals(t.name()) ? "state: CardStateName; " : "");
            objects.add(head + "props: " + t.propsType() + " }");
            patches.add(head + "props: Patch<" + t.propsType() + "> }");
        }
        o.union("export type WireObjectType =", typeNames);
        o.line("/** A change to some properties; null puts a property back to its default. */");
        o.line("export type Patch<P> = { [K in keyof P]?: P[K] | null };");
        o.blank();
        o.rawUnion("export type WireObject =", objects);
        o.rawUnion("export type WireObjectPatch =", patches);

        o.section("Envelope: server -> client JSON text frames");
        o.block("export interface LogEntry", List.of("type: GameLogEntryType;", "msg: string;"));
        List<String> messageNames = new ArrayList<>();
        for (WireEnvelope.Message msg : WireEnvelope.MESSAGES) {
            messageNames.add(msg.tsName());
            List<String> fields = new ArrayList<>();
            for (WireEnvelope.Field f : msg.fields()) {
                if (f.doc() != null) {
                    fields.add("/** " + f.doc() + " */");
                }
                fields.add(f.name() + (f.optional() ? "?: " : ": ") + f.ts() + ";");
            }
            o.line("/** " + msg.doc() + " */");
            o.block("export interface " + msg.tsName(), fields);
        }
        o.line("export type ServerMessage = " + String.join(" | ", messageNames) + ";");
        o.blank();

        o.section("Protocol (ProtocolMethod). Arguments are positional; unknown = no wire form yet");
        List<String> directions = new ArrayList<>();
        List<String> server = new ArrayList<>();
        List<String> client = new ArrayList<>();
        List<String> returns = new ArrayList<>();
        for (WireModel.Method meth : m.methods()) {
            directions.add(meth.name() + ": '" + (meth.server() ? "server" : "client") + "',");
            (meth.server() ? server : client).add(meth.name() + ": [" + String.join(", ", meth.args()) + "];");
            returns.add(meth.name() + ": " + meth.returns() + ";");
        }
        o.line("/** Who calls each method: 'server' = game to player (IGuiGame), 'client' = player to game (IGameController). */");
        o.block("export const PROTOCOL_METHODS =", directions, " as const;");
        o.line("export type ProtocolMethodName = keyof typeof PROTOCOL_METHODS;");
        o.blank();
        o.block("export interface ServerProtocolArgs", server);
        o.block("export interface ClientProtocolArgs", client);
        o.line("export type ServerMethod = keyof ServerProtocolArgs;");
        o.line("export type ClientMethod = keyof ClientProtocolArgs;");
        o.blank();
        o.line("/** Java return type of each method; undefined = no reply. */");
        o.block("export interface ProtocolReturns", returns);
        return o.toString();
    }

    private static List<String> props(WireModel m, String objectType) {
        List<String> out = new ArrayList<>();
        for (WireModel.Property p : m.properties()) {
            if (objectType == null || p.objectTypes().contains(objectType)) {
                out.add(p.name() + "?: " + tsType(p) + ";");
            }
        }
        return out;
    }

    /** Value shapes as {@code forge.web.bridge.WireEncoder} writes them. */
    static String tsType(WireModel.Property p) {
        return switch (p.kind()) {
            case CARD -> "CardId";
            case CARDS -> "CardId[]";
            case PLAYER -> "PlayerId";
            case PLAYERS -> "PlayerId[]";
            case STACK_ITEM -> "StackItemId";
            case STACK_ITEMS -> "StackItemId[]";
            case ENTITY -> "EntityRef";
            case CARD_STATE -> "CardStateName";
            case COMBAT -> "CombatBand[]";
            case BOOL -> "boolean";
            case INT, FLOAT -> "number";
            case STRING, MANA_COST, COLORS, CARD_TYPE -> "string";
            case ENUM -> {
                if (p.enumType() == null) {
                    throw new IllegalStateException("enum property " + p.name() + " has no enum type");
                }
                yield p.enumType();
            }
            case COUNTERS, INT_MAP, MANA_MAP -> "Record<string, number>";
            case KEYWORDS, STRING_LIST, STRING_SET -> "string[]";
            case PAPER_CARD -> "PaperCardRef";
            case STRING_MAP -> "Record<string, string>";
            case INT_SET -> "number[]";
            case GENERIC_MAP -> "Record<string, unknown>";
            case OBJECT -> "unknown";
        };
    }

    /** Line writer; two-space indent, LF endings. */
    private static final class Out {
        private final StringBuilder sb = new StringBuilder();

        void line(String s) {
            sb.append(s).append('\n');
        }

        boolean has(String s) {
            return sb.indexOf(s) >= 0;
        }

        /** An empty line, never two in a row. */
        void blank() {
            if (sb.length() > 0 && !sb.toString().endsWith("\n\n")) {
                sb.append('\n');
            }
        }

        void section(String title) {
            blank();
            line("// ---- " + title + " ----");
            blank();
        }

        void block(String head, List<String> body) {
            block(head, body, "");
        }

        void block(String head, List<String> body, String tail) {
            line(head + " {");
            for (String b : body) {
                line("  " + b);
            }
            line("}" + tail);
            blank();
        }

        void union(String head, List<String> members) {
            List<String> quoted = new ArrayList<>();
            for (String mem : members) {
                quoted.add("'" + mem + "'");
            }
            rawUnion(head, quoted);
        }

        void rawUnion(String head, List<String> members) {
            line(head);
            for (int i = 0; i < members.size(); i++) {
                line("  | " + members.get(i) + (i == members.size() - 1 ? ";" : ""));
            }
            blank();
        }

        @Override
        public String toString() {
            // one trailing newline at end of file
            return sb.toString().replaceAll("\n+$", "\n");
        }
    }
}
